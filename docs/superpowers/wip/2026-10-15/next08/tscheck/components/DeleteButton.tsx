// クライアントコンポーネント宣言：useState や onClick を使うために必須
"use client";

// 削除中フラグ管理用
import { useState } from "react";
// 削除後の遷移用
import { useRouter } from "next/navigation";
// ブラウザ向け Supabase クライアント
import { createClient } from "@/lib/supabase/client";

// -------------------------------------------------
// Props の型定義
// -------------------------------------------------
// bookId:    削除対象の書籍ID。
//            Supabase の DELETE クエリの WHERE 句で
//            使用します。
// bookTitle: 確認ダイアログに表示する書籍タイトル。
//            ユーザーが削除対象を確認できるように
//            するために使用します。
// -------------------------------------------------
type Props = {
  bookId: string;
  bookTitle: string;
};

export default function DeleteButton({ bookId, bookTitle }: Props) {
  // 削除後に一覧へ遷移するために使用
  const router = useRouter();

  // -------------------------------------------------
  // 状態管理
  // -------------------------------------------------
  // isDeleting: 削除処理中かどうかを管理します。
  //             true の間はボタンを無効化し、
  //             テキストを「削除中...」に変更して、
  //             二重送信を防ぎます。
  // -------------------------------------------------
  const [isDeleting, setIsDeleting] = useState(false);

  // -------------------------------------------------
  // 削除処理ハンドラ
  // -------------------------------------------------
  // async 関数なので、内部で await を使えます。
  // -------------------------------------------------
  const handleDelete = async () => {
    // -------------------------------------------------
    // 1. 確認ダイアログの表示
    // -------------------------------------------------
    // window.confirm() はブラウザ標準の確認ダイアログ
    // を表示します。ユーザーが「OK」をクリックすると
    // true、「キャンセル」をクリックすると false を
    // 返します。
    //
    // 確認ダイアログのメッセージには書籍タイトルを
    // 含め、削除対象が明確になるようにします。
    // \n で改行を入れています。
    // -------------------------------------------------
    const confirmed = window.confirm(
      `本当に「${bookTitle}」を削除しますか？\nこの操作は取り消せません。`
    );

    // -------------------------------------------------
    // キャンセルされた場合は何もしない
    // -------------------------------------------------
    // 早期 return パターン。深いネストを避けて
    // 読みやすくする定番の書き方です。
    // -------------------------------------------------
    if (!confirmed) {
      return;
    }

    // -------------------------------------------------
    // 2. 削除処理の実行
    // -------------------------------------------------
    // ローディング状態に切り替え
    setIsDeleting(true);

    try {
      // Supabase クライアントを準備
      const supabase = createClient();

      // -------------------------------------------------
      // Supabase DELETE クエリ
      // -------------------------------------------------
      // .from("books") で books テーブルを指定し、
      // .delete() で削除操作を行います。
      // .eq("id", bookId) で削除対象を書籍IDで
      // 絞り込みます。
      //
      // ※ .eq() を付けずに .delete() だけを実行すると
      //    テーブルの全データが削除されるので、
      //    必ず WHERE 条件を指定してください。
      //    (※実際には RLS や Supabase の安全装置で
      //    そう簡単には全削除されませんが、習慣として
      //    必ず付けるクセを付けましょう)
      // -------------------------------------------------
      const { error } = await supabase
        .from("books")
        // DELETE 文に相当
        .delete()
        // WHERE id = bookId
        .eq("id", bookId);

      if (error) {
        // catch にエラーを渡す
        throw error;
      }

      // -------------------------------------------------
      // 3. 削除成功: 一覧ページにリダイレクト
      // -------------------------------------------------
      // 削除した書籍の詳細ページはもう存在しないため、
      // 一覧ページに遷移します。
      // router.refresh() でサーバーコンポーネントの
      // データを再取得し、削除された書籍が一覧から
      // 消えていることを確認できるようにします。
      // -------------------------------------------------
      // 一覧ページへ
      router.push("/books");
      // サーバー側データを再取得
      router.refresh();
    } catch (err) {
      console.error("削除エラー:", err);
      // -------------------------------------------------
      // エラーが発生した場合はアラートで通知
      // -------------------------------------------------
      // alert はブラウザ標準のメッセージダイアログ。
      // 簡易的なエラー表示として使っています。
      // -------------------------------------------------
      alert("書籍の削除に失敗しました。もう一度お試しください。");
      // 状態を戻してリトライ可能に
      setIsDeleting(false);
    }
  };

  // -------------------------------------------------
  // ボタンのレンダリング
  // -------------------------------------------------
  // 削除ボタンは赤色で表示し、危険な操作であることを
  // 視覚的に示します。
  // 削除処理中はボタンを無効化し、テキストを
  // 「削除中...」に変更して、処理中であることを
  // ユーザーに伝えます。
  // -------------------------------------------------
  return (
    <button
      // クリックで削除ハンドラを呼ぶ
      onClick={handleDelete}
      // 削除中はクリック不可
      disabled={isDeleting}
      className="inline-flex items-center px-4 py-2 border border-transparent text-sm font-medium rounded-md shadow-sm text-white bg-red-600 hover:bg-red-700 focus:outline-none focus:ring-2 focus:ring-offset-2 focus:ring-red-500 disabled:opacity-50 disabled:cursor-not-allowed"
    >
      {/* 削除中はスピナー+「削除中...」を表示 */}
      {isDeleting ? (
        <>
          {/* -------------------------------------------
              ローディングスピナー
              削除処理中に表示される回転アニメーション
              です。ユーザーに処理中であることを
              視覚的にフィードバックします。
          ------------------------------------------- */}
          <svg
            // animate-spin で回転アニメ
            className="animate-spin -ml-1 mr-2 h-4 w-4 text-white"
            xmlns="http://www.w3.org/2000/svg"
            fill="none"
            viewBox="0 0 24 24"
          >
            <circle
              // 25% の透明度で薄く描画
              className="opacity-25"
              cx="12"
              cy="12"
              r="10"
              stroke="currentColor"
              strokeWidth="4"
            />
            <path
              // 75% の透明度でやや濃く描画
              className="opacity-75"
              fill="currentColor"
              // スピナーの一部円弧
              d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4zm2 5.291A7.962 7.962 0 014 12H0c0 3.042 1.135 5.824 3 7.938l3-2.647z"
            />
          </svg>
          削除中...
        </>
      ) : (
        <>
          {/* ゴミ箱アイコン */}
          <svg
            className="w-4 h-4 mr-2"
            fill="none"
            stroke="currentColor"
            viewBox="0 0 24 24"
          >
            <path
              strokeLinecap="round"
              strokeLinejoin="round"
              strokeWidth={2}
              // ゴミ箱の絵
              d="M19 7l-.867 12.142A2 2 0 0116.138 21H7.862a2 2 0 01-1.995-1.858L5 7m5 4v6m4-6v6m1-10V4a1 1 0 00-1-1h-4a1 1 0 00-1 1v3M4 7h16"
            />
          </svg>
          削除する
        </>
      )}
    </button>
  );
}
