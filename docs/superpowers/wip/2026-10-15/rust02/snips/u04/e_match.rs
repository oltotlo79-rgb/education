fn main() {
    for code in [200, 202, 301, 404, 418, 503, 999] {
        // match は値を上から順に比べ、最初に合った「腕」を実行する
        let label = match code {
            // 1つの値
            200 => "成功",
            // | は「または」
            201 | 202 => "受け付けました",
            // ..= は範囲（300 以上 399 以下）
            300..=399 => "リダイレクト",
            404 => "見つかりません",
            400..=499 => "リクエストの誤り",
            500..=599 => "サーバーの誤り",
            // _ は「ここまでのどれにも当てはまらない、それ以外すべて」
            _ => "不明なコード",
        };
        println!("{code}: {label}");
    }
}
