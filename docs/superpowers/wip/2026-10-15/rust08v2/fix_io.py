import sys
def edit(p, reps):
    s = open(p, encoding="utf-8").read()
    for a, b in reps:
        n = s.count(a)
        if n != 1:
            sys.exit(f"{p}: count {n}: {a[:50]}")
        s = s.replace(a, b)
    open(p, "w", encoding="utf-8").write(s)

